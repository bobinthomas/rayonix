/**
 * Generates src/lib/cms/seed.sql from static content files
 * (src/content/news.ts, src/content/company/blog.ts, src/content/careers.ts)
 * so Cloudflare D1 can be seeded with existing content:
 *
 *   node scripts/seed-cms.mjs
 *   wrangler d1 execute rayonix-db --file=src/lib/cms/seed.sql
 */

import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import ts from "typescript";

const root = process.cwd();

function loadTsModule(relPath) {
  const fullPath = path.join(root, relPath);
  const src = fs.readFileSync(fullPath, "utf8");
  const { outputText } = ts.transpileModule(src, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  });
  const mod = { exports: {} };
  const fn = new vm.Script(`(function(exports, require, module) {\n${outputText}\n})`).runInThisContext();
  fn(mod.exports, () => ({}), mod);
  return mod.exports;
}

const sqlStr = (val) => {
  if (val === null || val === undefined) return "NULL";
  return `'${String(val).replace(/'/g, "''")}'`;
};

const newsMod = loadTsModule("src/content/news.ts");
const blogMod = loadTsModule("src/content/company/blog.ts");
const careersMod = loadTsModule("src/content/careers.ts");

const lines = [
  "-- Auto-generated by scripts/seed-cms.mjs",
  "-- Safe to re-run: uses INSERT OR IGNORE on unique slugs.",
  "",
];

(newsMod.NEWS ?? []).forEach((item, idx) => {
  lines.push(
    `INSERT OR IGNORE INTO news_stories (slug, kind, published, homepage, category, published_date, title, summary_json, body_json, coverage_url, source, image_src, image_alt, buttons_json, source_link_json, related_json, sort_order) VALUES (${[
      sqlStr(item.slug),
      sqlStr(item.kind),
      item.published ? 1 : 0,
      item.homepage ? 1 : 0,
      sqlStr(item.category),
      sqlStr(item.date ?? null),
      sqlStr(item.title),
      sqlStr(JSON.stringify(item.summary ?? [])),
      item.article?.body ? sqlStr(JSON.stringify(item.article.body)) : "NULL",
      sqlStr(item.coverageUrl ?? null),
      sqlStr(item.source ?? null),
      sqlStr(item.image?.src ?? null),
      sqlStr(item.image?.alt ?? null),
      sqlStr(JSON.stringify(item.buttons ?? [])),
      item.article?.sourceLink ? sqlStr(JSON.stringify(item.article.sourceLink)) : "NULL",
      sqlStr(JSON.stringify(item.article?.related ?? [])),
      idx,
    ].join(", ")});`
  );
});

lines.push("");

(blogMod.blogPosts ?? []).forEach((post) => {
  lines.push(
    `INSERT OR IGNORE INTO blog_posts (slug, title, published_date, summary, body_json, cover_image, published) VALUES (${[
      sqlStr(post.slug),
      sqlStr(post.title),
      sqlStr(post.date),
      sqlStr(post.summary),
      sqlStr(JSON.stringify(post.body ?? [])),
      "NULL",
      1,
    ].join(", ")});`
  );
});

lines.push("");

(careersMod.ROLES ?? []).forEach((role, idx) => {
  lines.push(
    `INSERT INTO career_roles (title, team, location, type, description, apply_url, published, sort_order) VALUES (${[
      sqlStr(role.title),
      sqlStr(role.team),
      sqlStr(role.location),
      sqlStr(role.type),
      "NULL",
      sqlStr(role.applyUrl),
      1,
      idx,
    ].join(", ")});`
  );
});

const outPath = path.join(root, "src/lib/cms/seed.sql");
fs.writeFileSync(outPath, lines.join("\n") + "\n", "utf8");
console.log(`Wrote ${outPath} (${newsMod.NEWS?.length ?? 0} news, ${blogMod.blogPosts?.length ?? 0} blog, ${careersMod.ROLES?.length ?? 0} roles)`);
